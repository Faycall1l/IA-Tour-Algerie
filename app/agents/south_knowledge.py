"""South-Algeria agent knowledge — compact DB-derived briefing.

Loads `app/agents/data/south_knowledge.json` (generated by
`scripts/data/generate_south_knowledge.py`) once and renders a compact
markdown briefing that agents can rely on for deep-south destinations
(reach, stays, restaurants, featured POIs). Everything in the briefing
is real data from the database — nothing fabricated.

`south_briefing(query)` returns the briefing text only when the query
references the south (wilaya names, Sahara/desert keywords, Tassili/
Ahaggar, etc.), so northern queries stay lean.
"""

