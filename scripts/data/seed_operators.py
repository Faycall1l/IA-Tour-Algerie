def seed():
    with engine.connect() as conn:
        for op in OPERATORS:
            existing = conn.execute(
                text("SELECT id FROM transport_operators WHERE name = :name"),
                {"name": op["name"]}
            ).fetchone()
            params = {
                "name": op["name"], "name_ar": op["name_ar"], "mode": op["mode"],
                "phone": op["phone"], "website": op["website"], "email": op["email"],
                "wilaya": op["headquarters_wilaya_id"],
                "description": op["description"], "coverage": op["coverage_type"],
            }
            if existing:
                conn.execute(text("""UPDATE transport_operators SET name_ar = :name_ar, mode = :mode, phone = :phone, website = :website, email = :email, headquarters_wilaya_id = :wilaya, description = :description, coverage_type = :coverage, updated_at = NOW() WHERE name = :name"""), params)
            else:
                params["id"] = uuid.uuid4()
                conn.execute(text("""INSERT INTO transport_operators (id, name, name_ar, mode, phone, website, email, headquarters_wilaya_id, description, coverage_type, is_active, metadata, created_at, updated_at) VALUES (:id, :name, :name_ar, :mode, :phone, :website, :email, :wilaya, :description, :coverage, true, '{}'::jsonb, NOW(), NOW())"""), params)
        conn.commit()
    print(f"Seeded {len(OPERATORS)} transport operators")

